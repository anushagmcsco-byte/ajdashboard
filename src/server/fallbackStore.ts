// Safe helper to execute DB query with fallback
export async function safeExecute<T>(
  dbAction: () => Promise<T>,
  fallbackAction: () => T | Promise<T>,
  context: string
): Promise<T> {
  try {
    return await dbAction();
  } catch (err: any) {
    console.warn(`[Safe Storage Layer] DB operation failed for ${context}: ${err?.message || err}. Utilizing resilient store.`);
    return await fallbackAction();
  }
}
